import streamlit as st
import pandas as pd
import numpy as np
import joblib
import os

# Load trained model
BASE_DIR = os.path.dirname(os.path.abspath(__file__))

model_path = os.path.join(BASE_DIR, "diabetes_model.pkl")

model = joblib.load(model_path)

# Website title
st.title("Diabetes Prediction System")

st.write("Enter Patient Details")

# User inputs
pregnancies = st.number_input("Pregnancies", 0, 20, 1)
glucose = st.number_input("Glucose", 0, 250, 120)
bp = st.number_input("Blood Pressure", 0, 150, 70)
skin = st.number_input("Skin Thickness", 0, 100, 20)
insulin = st.number_input("Insulin", 0, 900, 80)
bmi = st.number_input("BMI", 0.0, 70.0, 25.0)
dpf = st.number_input(
    "Diabetes Pedigree Function", 0.0, 3.0, 0.5
)
age = st.number_input("Age", 1, 100, 30)

# Prediction button
if st.button("Predict"):

    data = pd.DataFrame([{
        'Pregnancies': pregnancies,
        'Glucose': glucose,
        'BloodPressure': bp,
        'SkinThickness': skin,
        'Insulin': insulin,
        'BMI': bmi,
        'DiabetesPedigreeFunction': dpf,
        'Age': age
    }])

    # Handle zero values
    cols = [
        'Glucose', 'BloodPressure',
        'SkinThickness', 'Insulin', 'BMI'
    ]

    data[cols] = data[cols].replace(0, np.nan)

    # Make prediction
    prediction = model.predict(data)[0]

    probability = model.predict_proba(data)[0][1]

    if prediction == 1:
        st.warning("Prediction: Diabetes")
    else:
        st.success("Prediction: No Diabetes")

    st.write(
        "Predicted Diabetes Probability:",
        round(probability * 100, 2), "%"
    )

    st.caption(
        "This is an educational machine learning project, "
        "not a medical diagnosis."
    )